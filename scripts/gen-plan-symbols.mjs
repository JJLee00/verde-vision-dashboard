#!/usr/bin/env node
// Writes the viewer's plan-symbol table out for the Vision Pro app, whose
// blueprint PDF draws from it — so the printed sheet and plan mode here are
// one drawing at one size, not two tables that drift.
//
// They had drifted badly (Oct 16 2026): the PDF kept its own name-substring
// lookup, matched this file on six species, printed about twenty more as a
// bare "PL" circle, and — because its schedule grouped rows by code — merged
// different plants into one line under one name.
//
// The table is authored HERE (src/lib/viewer/symbols.ts + the codes and
// names in catalog.ts). The app owns spread (PlantItem.matureWidthFt), so
// the width written below is only the fallback this viewer also uses for
// models the app no longer ships.
//
//   npm run gen:plan-symbols            write the app's copy
//   npm run check:plan-symbols          fail if the app's copy is behind
//
//   node scripts/gen-plan-symbols.mjs [--check] [path/to/plan-symbols.json]

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": join(root, "src") } });
const { SYMBOLS, BY_KIND, symbolFor, edgeRadius, rngFor } = await jiti.import(
  join(root, "src/lib/viewer/symbols.ts"),
);
const { CATALOG, speciesMeta } = await jiti.import(join(root, "src/lib/viewer/catalog.ts"));

const args = process.argv.slice(2);
const check = args.includes("--check");
const OUT =
  args.find((a) => !a.startsWith("--")) ??
  join(process.env.HOME ?? "", "Verde-Vision/Test/Test/Blueprint/plan-symbols.json");

// Four places is a hundredth of a millimetre on a 30 ft canopy — and it
// keeps trig noise (6e-17 for a zero) out of the file.
const round = (v) =>
  typeof v === "number"
    ? Math.round(v * 1e4) / 1e4 + 0
    : Array.isArray(v)
      ? v.map(round)
      : v && typeof v === "object"
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, round(x)]))
        : v;

// Each distinct drawing once; models point at it by index. A mulga is 156
// limbs and two models share it.
const symbols = [];
const indexOf = new Map();
const intern = (sym) => {
  if (!sym) return null;
  const json = JSON.stringify(round(sym));
  if (!indexOf.has(json)) {
    indexOf.set(json, symbols.length);
    symbols.push(json);
  }
  return indexOf.get(json);
};

const models = {};
for (const model of [...new Set([...Object.keys(CATALOG), ...Object.keys(SYMBOLS)])].sort()) {
  const meta = speciesMeta(model);
  models[model] = {
    code: meta.code,
    name: meta.name,
    kind: meta.kind,
    fallbackWidthFt: CATALOG[model]?.matureWidthFt ?? meta.matureWidthFt,
    symbol: intern(symbolFor(model, meta.kind)),
  };
}

const kinds = {};
for (const kind of Object.keys(BY_KIND).sort()) kinds[kind] = intern(BY_KIND[kind]);

// What the app's port is checked against: this file's own jitter and edge
// functions, run here, so a change to either fails the app's tests rather
// than quietly drawing something else.
const rng = rngFor("MulgaAcaciaLg");
const edges = [];
for (const [i, json] of symbols.entries()) {
  const sym = JSON.parse(json);
  for (const t of [-2.5, -0.3, 0, 0.7, 1.9, 4.4]) {
    edges.push({ symbol: i, t, r: Math.round(edgeRadius(sym, t) * 1e9) / 1e9 });
  }
}

const lines = [
  "{",
  `  "source": "verde-vision-dashboard src/lib/viewer/symbols.ts + catalog.ts — generated by scripts/gen-plan-symbols.mjs, do not edit by hand",`,
  `  "fallbackKind": "rosette",`,
  `  "kinds": ${JSON.stringify(kinds)},`,
  `  "models": {`,
  Object.entries(models)
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(round(v))}`)
    .join(",\n"),
  `  },`,
  `  "symbols": [`,
  symbols.map((s) => `    ${s}`).join(",\n"),
  `  ],`,
  `  "parity": {`,
  `    "rngSeed": "MulgaAcaciaLg",`,
  `    "rng": ${JSON.stringify(Array.from({ length: 8 }, () => rng()))},`,
  `    "edges": [`,
  edges.map((e) => `      ${JSON.stringify(e)}`).join(",\n"),
  `    ]`,
  `  }`,
  "}",
  "",
];
const out = lines.join("\n");
JSON.parse(out); // never write a file the app can't decode

if (check) {
  if (!existsSync(OUT)) {
    console.log(`FAIL   no app copy at ${OUT}`);
    process.exit(1);
  }
  if (readFileSync(OUT, "utf8") !== out) {
    console.log(`FAIL   the app's plan-symbols.json is behind symbols.ts — run npm run gen:plan-symbols`);
    process.exit(1);
  }
  console.log(`ok     ${Object.keys(models).length} models, ${symbols.length} drawings — the app's copy is current`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote  ${OUT}: ${Object.keys(models).length} models, ${symbols.length} drawings`);
}
